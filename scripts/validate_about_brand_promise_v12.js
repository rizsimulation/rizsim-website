/* Fix 4 - Brand Promise About: canonical content, source fidelity and safe sharing. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const text=n=>fs.readFileSync(path.join(root,n),'utf8');
const pub=text('about.html');
const student=text('access-in.html');
const authenticated=text('access-out.html');
const style=text('rizsim-brand-about.css');
const share=text('rizsim-shared-about.js');
const pdf=fs.readFileSync(path.join(root,'RizSim_Brand_Promise.pdf'));
assert.match(pub,/<main id="rizsimBrandAbout" class="page-content rz-about"/,'Keep approved public page transition / swipe class');
assert.match(pub,/<link rel="stylesheet" href="rizsim-brand-about.css">/);
assert.equal((pub.match(/<main\b/g)||[]).length,1);
assert.equal((pub.match(/href="RizSim_Brand_Promise\.pdf"/g)||[]).length,2,'One Read + one Download PDF');
assert.match(pub,/Read the Brand Promise/);
assert.match(pub,/download="RizSim_Brand_Promise.pdf"/);
assert.match(pub,/target="_blank" rel="noopener noreferrer"/);
assert.match(pub,/To transform learning from the acquisition of knowledge into the development of/);
assert.match(pub,/A concept experienced can be understood/);
assert.doesNotMatch(pub,/class="about-(?:approach|access-model|audience)-/,'Remove repetitive old public About sections');
assert.ok(pub.indexOf('id="rizsimBrandAbout"')<pub.indexOf('<footer class="site-footer"'),'Keep official public footer');
for(const [label,html,nav] of [['Student',student,'data-student-view="about"'],['Other authenticated',authenticated,'data-auth-view="about"']]){
 assert.match(html,new RegExp(nav));
 assert.match(html,/<link rel="stylesheet" href="rizsim-brand-about\.css">/);
 assert.match(html,/<script src="rizsim-shared-about\.js" defer><\/script>/);
 assert.match(html,/<div id="rizsimSharedAbout" class="rz-about" hidden/);
 assert.match(html,/<div id="rizsimLegacyAbout" class="content-shell">/);
 assert.equal((html.match(/id="rizsimSharedAbout"/g)||[]).length,1,label+' has one shared mount');
 assert.equal((html.match(/id="rizsimLegacyAbout"/g)||[]).length,1,label+' retains fallback');
}
assert.match(share,/fetch\('about\.html'/);
assert.match(share,/main#rizsimBrandAbout\.rz-about/);
assert.match(share,/mount\.innerHTML=source\.innerHTML/);
assert.match(share,/legacy\.hidden=true/);
assert.match(share,/legacy\.hidden=false/);
assert.match(share,/classList\.add\('rizsim-unified-about'\)/);
assert.match(share,/classList\.remove\('rizsim-unified-about'\)/);
assert.match(share,/console\.warn\('RizSim shared About fallback:/);
assert.match(style,/\.rz-about \.rz-about-hero/);
assert.match(style,/#view-about\.rizsim-unified-about\{padding:0;overflow:hidden\}/);
assert.match(style,/@media\(max-width:600px\)/);
assert.match(style, /prefers-reduced-motion:reduce/);
assert.doesNotMatch(style,/(^|\n)\s*body\s*\{/,'About CSS must not redefine global body');
assert.equal(pdf.subarray(0,5).toString(),'%'+'PDF-');
assert.ok(pdf.length>10000&&pdf.length<150000,'PDF is nonempty and lightweight');
const source=pdf.toString('ascii');
assert.ok(source.trimEnd().endsWith('%%EOF'),'PDF EOF marker present');
const m=source.match(/startxref\n(\d+)\n%%EOF/);
assert.ok(m,'PDF XREF lookup present');
assert.equal(source.slice(Number(m[1]),Number(m[1])+4),'xref','PDF XREF byte positions valid');
assert.match(source,/The RizSim Learning Journey/);
assert.match(source,/Our Purpose/);
assert.match(source,/Our Philosophy/);
assert.match(source,/The RizSim Difference/);
assert.match(source,/Explore/);
assert.match(source,/application\/pdf|\/Type \/Catalog/);
console.log('PASS: canonical public, Student and all authenticated About views; faithful Brand Promise PDF and fallback.');